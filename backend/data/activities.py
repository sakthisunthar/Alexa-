def get_activities_for_destination(destination_key: str) -> list[dict]:
    return ACTIVITIES.get(destination_key, [])


def filter_activities(
    destination_key: str, interests: list[str], limit: int = 20
) -> list[dict]:
    all_acts = get_activities_for_destination(destination_key)
    if not interests:
        return all_acts[:limit]

    interest_set = {i.lower() for i in interests}
    scored = []
    for act in all_acts:
        score = len(interest_set & set(act["interests"]))
        scored.append((score, act))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [act for _, act in scored[:limit]]
